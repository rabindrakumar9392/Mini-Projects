function createCard(movie) {
  let card = document.createElement("div");
  card.setAttribute("class", "movie");
  let movieImage = document.createElement("img");
  movieImage.setAttribute("src", movie.image)
  let movieName = document.createElement("h2");
  movieName.innerText = movie.movieName;
  let ageLimit = document.createElement("p");
  ageLimit.innerText = movie.ageLimit;
  let language = document.createElement("p");
  language.innerText = movie.language;
  let price = document.createElement("p");
  price.innerText = `price : ${movie.price}`

  let viewMore = document.createElement("button");
  viewMore.innerText = "VIEW MORE";

  let addToCart = document.createElement("button");
  addToCart.innerText = "Add To Cart";

  viewMore.addEventListener("click", () => {
    localStorage.setItem("movie", JSON.stringify(movie));
    console.log("viewmore called", movie)
    window.location.href = "http://localhost:5500/Dom/viewMore.html";
  })

  addToCart.addEventListener("click", () => {

    if (currUser != null) {
      for(let i=0; i<users.length; i++){
        if(currUser.mobile == users[i].mobile){
          users[i].cart.push(movie);
        }
      }

      localStorage.setItem("users", JSON.stringify(users));
    }
    else{
      alert("login first");
    }


  })

  card.append(movieImage, movieName, ageLimit, language, price, viewMore, addToCart);
  container.append(card);


}


function showMovies(movies) {
  container.innerHTML = "";
  for (let i = 0; i < movies.length; i++) {
    createCard(movies[i]);
  }
}

