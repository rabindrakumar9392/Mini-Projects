dropDown.addEventListener("change", (event) => {
  if (event.target.value == "price_asc") {
    data.sort((a, b) => a.price - b.price);
    showMovies(data);
  }
  else if (event.target.value == "price_desc") {
    data.sort((a, b) => b.price - a.price);
    showMovies(data);
  }
  else if (event.target.value == "name_asc") {
    data.sort((a, b) => a.movieName.localeCompare(b.movieName));
    showMovies(data);
  }
  else if (event.target.value == "name_desc") {
    data.sort((a, b) => b.movieName.localeCompare(a.movieName));
    showMovies(data);
  }
  else if (event.target.value == "reset") {
    showMovies(copyData);
  }
})



